def is_XMailer_result_suspect(Xmail_result):
    if Xmail_result == "Missing":
        return 0.25

    Xmail_result = Xmail_result.lower().strip()

    if any(Xmailer in Xmail_result for Xmailer in suspect_Xmailer):
        return 1
    if any(Xmailer in Xmail_result for Xmailer in common_XMailer):
        return 0.1
    try:
        if Detector.is_gibberish(
            Xmail_result
        ):  # some of Xmailers are just random strings so it's detect very well this problem
            return 1
    except (
        ValueError
    ):  # and if it's too short it's weird too, usually we have the name of the program sender, and the version so it can't be short
        return 1
    return 0.5


def is_display_name_suspect(
    display_name,
):  # useful for public identities but not relevant for personal mails
    if (
        display_name == "Unknown"
    ):  # some mails in the database have no sender, absolutely weird (generally the mails are empty)
        return 1
    display_name = display_name.lower().strip()
    if display_name in public_identities:
        return 0
    if (
        get_best_jaro_score(string_substitutions_spoof(display_name), public_identities)
        > 0.8
    ):
        return 1
    return 0.25


def is_spam(label):  # ONLY FOR TRAINING
    if label == "spam":
        return 1
    if label == "ham":
        return 0
    return None


