def count_received_headers(msg):
    return len(msg.get_all("Received") or [])


def count_duplicate_from_headers(msg):
    count = len(msg.get_all("From") or [])
    return max(count - 1, 0)


def count_duplicate_subject_headers(msg):
    count = len(msg.get_all("Subject") or [])
    return max(count - 1, 0)


def count_duplicate_content_type_headers(msg):
    count = len(msg.get_all("Content-Type") or [])
    return max(count - 1, 0)


def count_duplicate_message_id_headers(msg):
    count = len(msg.get_all("Message-ID") or [])
    return max(count - 1, 0)


def has_message_id(msg):
    return 0 if msg.get("Message-ID") else 1


def count_x_headers(msg):
    return sum(1 for key in msg.keys() if key.lower().startswith("x-"))
