from .constants import (
    safe_file_extensions,
    executable_file_extensions,
    common_file_extensions,
    suspect_file_extensions,
    file_extensions,
)

# Actually, theses features are nearly useless since the training dataset has 4k attachments for 36k mails, and like 0 attachments attacks
